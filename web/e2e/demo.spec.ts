test('staff creates incident and notes survive reload',async({page,context})=>{
 await page.goto('/control');
 await page.getByLabel('Email',{exact:true}).fill(process.env.STAFF_ADMIN_EMAIL!);
 await page.getByLabel('Password',{exact:true}).fill(process.env.STAFF_ADMIN_PASSWORD!);
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page.getByText('Trail Operations & Incident Desk')).toBeVisible();
 const scenario=await context.request.post('/api/v1/ops/demo/scenario',{data:{name:'fast-ascent'}});
 expect(scenario.ok()).toBeTruthy();const group=await scenario.json();
 await page.goto('/control/groups/'+group.id);
 await page.getByRole('combobox',{name:'Incident type',exact:true}).selectOption('assistance');
 const note='Demo assistance '+Date.now();await page.getByLabel('Notes',{exact:true}).fill(note);
 await page.getByRole('button',{name:'Create incident',exact:true}).click();
 await expect(page.getByText('Incident saved.',{exact:false})).toBeVisible();
 await page.reload();await expect(page.getByText(note,{exact:true})).toBeVisible();
 const details=await (await context.request.get('/api/v1/ops/groups/'+group.id)).json();
 expect(details.incidents.filter((i:any)=>i.notes===note)).toHaveLength(1);
 const status=await (await context.request.get('/api/v1/groups/'+group.code)).json();
 expect(status.incidents.some((i:any)=>i.id===details.incidents.find((i:any)=>i.notes===note).id)).toBeTruthy();
 await page.goto('/control/incidents');
 const created=await (await context.request.post('/api/v1/ops/incidents',{data:{group_id:group.id,type:'assistance',notes:'Live incoming incident'}})).json();
 const form=page.locator('form').filter({has:page.getByRole('heading',{name:'#'+created.id+' · assistance',exact:true})});
 await expect(form.getByRole('textbox',{name:'Notes',exact:true})).toHaveValue('Live incoming incident');
 await form.getByRole('textbox',{name:'Notes',exact:true}).fill('Unsaved desk note');
 await context.request.patch('/api/v1/ops/incidents/'+created.id,{data:{status:'assigned',assigned_to:'Rescue desk',notes:'Remote update'}});
 // Observe a completed refresh after the remote change before checking the draft.
 await page.waitForResponse(r=>r.url().endsWith('/api/v1/incidents')&&r.status()===200);
 await expect(form.getByRole('textbox',{name:'Notes',exact:true})).toHaveValue('Unsaved desk note');

});
